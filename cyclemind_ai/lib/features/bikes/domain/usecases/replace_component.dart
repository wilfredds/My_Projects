/// What recording a replacement actually did, so the UI can say so.
class ComponentReplaced {
  const ComponentReplaced({
    required this.removed,
    required this.fitted,
    required this.log,
    this.queued = false,
  });

  /// The part as it was before. Its wear is what [log] records.
  final BikeComponent removed;

  /// The part now in the slot: same id and type, wear from zero.
  final BikeComponent fitted;

  /// The service-history entry, written in the same atomic batch.
  final MaintenanceLog log;

  /// Saved on this device only: no signal, so the server hasn't confirmed it
  /// yet. It syncs on reconnect, and wear has already reset locally.
  final bool queued;

  /// Odometer reading at which the new part will first raise a reminder.
  double get nextReminderAtKm =>
      fitted.installedAtKm + fitted.lifespanKm * dueSoonWearFraction;
}

/// Records that a component was replaced. It resets the component's wear AND
/// appends a permanent service-history entry, as one atomic write.
///
/// Until this existed, a reminder could never be cleared: once a part crossed
/// 80% it read "due soon" forever, even after a new one went on. A reminder
/// you can't clear is one you learn to ignore.
///
/// Mirrors `LogRide`: validation and derivation live here, and atomicity lives
/// in [BikesRepository.replaceComponent].
class ReplaceComponent {
  const ReplaceComponent(this._bikes);
  final BikesRepository _bikes;

  /// [logId] MUST be generated by the caller and stay the same across retries
  /// of one replacement. A repeated id is denied by firestore.rules, which is
  /// what stops a retry recording the same replacement twice.
  Future<Result<ComponentReplaced>> call({
    required String logId,
    required String userId,
    required Bike bike,
    required String componentId,
    required String brand,
    required double lifespanKm,
    String note = '',
    DateTime? serviceDate,
  }) async {
    if (logId.isEmpty) {
      return Failure(const ValidationFailure('Missing replacement id.'));
    }
    if (userId.isEmpty || userId != bike.userId) {
      return Failure(
          const ValidationFailure('You can only service your own bikes.'));
    }
    final removed = componentById(bike, componentId);
    if (removed == null) {
      return Failure(const ValidationFailure(
          'That component is no longer on this bike.'));
    }
    final lifespanProblem = lifespanError(lifespanKm);
    if (lifespanProblem != null) {
      return Failure(ValidationFailure(lifespanProblem));
    }
    final trimmedNote = note.trim();
    if (trimmedNote.length > AppConstants.maxServiceNoteChars) {
      // const: interpolating a const int is itself a constant expression.
      return Failure(const ValidationFailure('Keep the note under '
          '${AppConstants.maxServiceNoteChars} characters.'));
    }
    final odometer = bike.totalMileageKm;
    if (!odometer.isFinite ||
        odometer < 0 ||
        odometer > AppConstants.maxOdometerKm) {
      return Failure(const ValidationFailure(
          'This bike\'s odometer reading is out of range.'));
    }

    final fitted = removed.refitted(
      odometerKm: odometer,
      brand: brand.trim(),
      lifespanKm: lifespanKm,
    );
    final log = MaintenanceLog(
      id: logId,
      userId: userId,
      bikeId: bike.id,
      component: logLabel(removed.type),
      mileageAtService: odometer,
      // The REMOVED part's status. "Replaced when overdue" is the useful
      // fact; the fitted part always reads OK, which would record nothing.
      status: statusForWear(removed.wearFraction(odometer)),
      serviceDate: serviceDate ?? DateTime.now(),
      // Clipped, never rejected: a legacy part with an enormous brand string
      // must still be replaceable.
      notes: clipUtf16(
        [
          replacementSummary(removed, fitted, odometer),
          if (trimmedNote.isNotEmpty) trimmedNote,
        ].join('\n\n'),
        AppConstants.maxLogNotesChars,
      ),
    );

    final saved = await _bikes.replaceComponent(
      bike: bike,
      replacement: fitted,
      log: log,
    );
    return saved.fold(
      Failure<ComponentReplaced>,
      (ack) => Success(ComponentReplaced(
        removed: removed,
        fitted: fitted,
        log: log,
        queued: ack == WriteAck.queued,
      )),
    );
  }
}

/// The `component` label a log is written with: the part's type, never
/// empty, and clipped to what `str(d.component, 80)` accepts.
///
/// Clipped rather than rejected. Component types are free text with no edit
/// screen, so rejecting would make a long-named part impossible to EVER mark
/// replaced. Every attempt would be denied by the rules.
String logLabel(String type) {
  final t = type.trim();
  return clipUtf16(
      t.isEmpty ? 'Component' : t, AppConstants.maxLogComponentChars);
}

/// [s] cut to at most [max] UTF-16 code units, without ever splitting a
/// surrogate pair.
///
/// Dart's `length` counts UTF-16 units. The rules' `size()` does not count
/// UTF-8 bytes (pinned by firestore-tests/premise.test.js C9), so a string
/// this short is accepted whether the rules count code points or units.
String clipUtf16(String s, int max) {
  if (s.length <= max) return s;
  var end = max;
  // A high surrogate just before the cut would leave half an emoji behind.
  final last = s.codeUnitAt(end - 1);
  if (last >= 0xD800 && last <= 0xDBFF) end -= 1;
  return s.substring(0, end);
}

/// The line every replacement writes into the log's notes: what came off, how
/// far it went, and what went on. `notes` is the only free-form field the
/// rules allow, so that is where this lives.
///
/// Guards every number: a legacy part can carry a NaN lifespan, and
/// `double.nan.round()` throws. That would crash the replacement of exactly
/// the parts most in need of one.
String replacementSummary(
  BikeComponent removed,
  BikeComponent fitted,
  double odometerKm,
) {
  final used = removed.usedKm(odometerKm);
  final life = removed.lifespanKm;
  final distance = used.isFinite ? ' after ${used.toStringAsFixed(0)} km' : '';
  final share = used.isFinite && life.isFinite && life > 0
      ? ' (${(used / life * 100).round()}% of ${life.toStringAsFixed(0)} km)'
      : '';
  return 'Removed ${_named(removed.brand, 'the old part')}$distance$share. '
      'Fitted ${_named(fitted.brand, 'a new part')}, '
      'lifespan ${fitted.lifespanKm.toStringAsFixed(0)} km.';
}

String _named(String brand, String fallback) {
  final b = clipUtf16(brand.trim(), AppConstants.maxComponentTextChars);
  return b.isEmpty ? fallback : b;
}

/// Snackbar text: what was recorded, when the next reminder will come, and
/// whether it's still waiting to sync.
String replacementMessage(ComponentReplaced r) {
  final base = '${r.log.component} replaced at '
      '${r.log.mileageAtService.toStringAsFixed(0)} km. '
      'Next reminder around ${r.nextReminderAtKm.toStringAsFixed(0)} km.';
  return r.queued ? '$base $savedOfflineNote' : base;
}
