import 'package:cyclemind_ai/core/utils/result.dart';
import 'package:cyclemind_ai/features/bikes/domain/entities/bike.dart';
import 'package:cyclemind_ai/features/bikes/domain/entities/maintenance_log.dart';

/// Contract for bike + maintenance persistence.
abstract interface class BikesRepository {
  Stream<List<Bike>> watchBikes(String userId);

  Future<Result<Bike>> addBike(Bike bike);

  /// Replaces a bike's tracked components.
  ///
  /// Deliberately CANNOT touch `totalMileageKm`. The previous `updateBike`
  /// wrote the whole document from a possibly-stale snapshot, so adding a
  /// component silently rolled the odometer back to whatever the screen last
  /// read. Narrowing the interface makes that impossible by construction
  /// rather than by convention: only logging or deleting a ride moves the
  /// odometer.
  Future<Result<Bike>> setComponents(String bikeId, List<BikeComponent> components);

  Future<Result<void>> deleteBike(String bikeId);

  /// Logs for one bike, scoped to [userId].
  ///
  /// The userId filter is NOT optional: Firestore evaluates read rules against
  /// a query's constraints and cannot filter, so a bikeId-only listen is
  /// rejected wholesale under owner-scoped rules.
  Stream<List<MaintenanceLog>> watchLogs(String userId, String bikeId);

  /// Records a replacement as ONE atomic write. The service-history entry
  /// [log] is created, and the component on [bike] that shares
  /// [replacement]'s id is swapped for it. Both land, or neither does.
  ///
  /// [MaintenanceLog.id] MUST be generated by the caller and STABLE ACROSS
  /// RETRIES. Logs are create-only (firestore.rules denies update), so
  /// re-sending the same id is rejected instead of recording the replacement
  /// twice. This is the same contract as `RidesRepository.addRide`.
  ///
  /// Writes `components` only and never `totalMileageKm`: the odometer comes
  /// from the stored document, not from [bike], which may be a stale
  /// snapshot.
  ///
  /// There is deliberately NO standalone "add log" method. A history entry
  /// without its reset, or a reset without its entry, is exactly the drift
  /// this pairing exists to prevent.
  Future<Result<void>> replaceComponent({
    required Bike bike,
    required BikeComponent replacement,
    required MaintenanceLog log,
  });
}

/// Why a [BikesRepository.replaceComponent] call is malformed, or null when it
/// is well formed.
///
/// Every implementation applies this before writing. The rules can't express
/// most of it, because nothing in them ties a log to the bike it describes.
String? replacementContractViolation({
  required Bike bike,
  required BikeComponent replacement,
  required MaintenanceLog log,
}) {
  if (log.id.isEmpty) return 'A replacement needs an id.';
  if (log.bikeId != bike.id) return 'That service entry is for another bike.';
  if (log.userId != bike.userId) return 'You can only service your own bikes.';
  final current = componentById(bike, replacement.id);
  if (current == null) return 'That component is no longer on this bike.';
  if (current.type != replacement.type) {
    return 'A replacement must be the same kind of part.';
  }
  return null;
}
